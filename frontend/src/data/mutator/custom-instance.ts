import z from 'zod';
import { MAUIDesktop } from '../../settings/globs-input/hooks/desktops/maui-desktop';

const baseURL = new URL(window.location.href).searchParams.get('server') || window.location.origin;

console.log('Server url =>', baseURL);

export const getApiFullUrl = (url: string) => `${baseURL}${url}`;

/**
 * API token, only required when the server is started with PKVAULT_API_TOKEN.
 * Stored per server, in the browser only.
 */
const TOKEN_STORAGE_KEY = `pkvault-api-token:${baseURL}`;

const getStoredApiToken = (): string | null => {
    try {
        return window.localStorage.getItem(TOKEN_STORAGE_KEY);
    } catch (_) {
        return null;
    }
};

const setStoredApiToken = (token: string | null): void => {
    try {
        if (token) {
            window.localStorage.setItem(TOKEN_STORAGE_KEY, token);
        } else {
            window.localStorage.removeItem(TOKEN_STORAGE_KEY);
        }
    } catch (_) {
        // storage not available: the token will be asked again
    }
};

export const hasStoredApiToken = (): boolean => !!getStoredApiToken();

// shared between concurrent requests failing at once, to ask the token only once
let tokenPrompt: Promise<string | null> | null = null;

const promptApiToken = (): Promise<string | null> => {
    tokenPrompt ??= Promise.resolve()
        .then(() => window.prompt('This PKVault server requires an access token (PKVAULT_API_TOKEN).')?.trim() || null)
        .finally(() => {
            tokenPrompt = null;
        });
    return tokenPrompt;
};

/**
 * Same as fetch, with the API token if any.
 * If the server answers 401, ask the token and retry once.
 */
export const fetchWithAuth = async (url: string, init?: RequestInit, isRetry = false): Promise<Response> => {
    const headers = new Headers(init?.headers);
    const token = getStoredApiToken();
    if (token) {
        headers.set('Authorization', `Bearer ${token}`);
    }

    const res = await fetch(url, { ...init, headers });

    if (res.status !== 401) {
        return res;
    }

    if (isRetry) {
        // the given token is wrong
        setStoredApiToken(null);
        return res;
    }

    const newToken = await promptApiToken();
    if (!newToken) {
        return res;
    }

    setStoredApiToken(newToken);
    return fetchWithAuth(url, init, true);
};

/**
 * Download a file from the API, for places where a simple link cannot send the token.
 */
export const downloadWithAuth = async (url: string): Promise<void> => {
    const targetUrl = getApiFullUrl(url);
    const res = await fetchWithAuth(targetUrl);

    if (!res.ok) {
        throw new QueryError(res);
    }

    const filename = /filename\*?=(?:UTF-8'')?"?([^";,]+)/i.exec(res.headers.get('Content-Disposition') ?? '')?.[ 1 ]
        ?? 'download';

    const objectUrl = URL.createObjectURL(await res.blob());
    try {
        const link = document.createElement('a');
        link.href = objectUrl;
        link.download = decodeURIComponent(filename);
        link.click();
    } finally {
        URL.revokeObjectURL(objectUrl);
    }
};

export type ResponseBack<D = unknown> = z.infer<typeof responseBackSchema> & { data: D }
export const responseBackSchema = z.object({
    // data: z.unknown(),
    headers: z.instanceof(Headers),
    status: z.number().int(),
});

export type SerializableResponse = Pick<Response, 'url' | 'ok' | 'status' | 'statusText' | 'headers'> & {
    body?: string;
};

export const customInstance = async <T extends ResponseBack>(url: string, init?: RequestInit): Promise<T> => {
    const targetUrl = normalizeUrlParams(getApiFullUrl(url));

    try {
        if (MAUIDesktop.isEnabled()) {

            const res = await MAUIDesktop.fetch(targetUrl, init);

            const headers = new Headers(res.headers);

            if (!res.ok) {
                throw new QueryError({ ...res, headers });
            }

            const body = res.body?.toString();
            const data = body ? JSON.parse(body) : {};

            return { data, status: res.status, headers } satisfies ResponseBack as T;
        }

        const res = await fetchWithAuth(targetUrl, init);

        if (!res.ok) {
            throw new QueryError(res);
        }

        const body = [ 204, 205, 304 ].includes(res.status) ? null : await res.text();
        const data = body ? JSON.parse(body) : {};

        return { data, status: res.status, headers: res.headers } satisfies ResponseBack as T;
    } catch (err) {
        if (err instanceof QueryError)
            throw err;

        if (err instanceof DOMException && err.name === 'AbortError') {
            throw err;
        }

        throw new QueryError({
            url: targetUrl,
            status: 500,
            statusText: 'Internal Error',
            headers: new Headers(),
        }, err instanceof Error ? err : undefined);
    }
};

/**
 * Normalize url params removing 'null' values generated by Orval.
 */
const normalizeUrlParams = (url: string): string => {
    const urlObj = new URL(url);

    const searchParams = new URLSearchParams();

    urlObj.searchParams.forEach((value, key) => {
        if (value !== 'null') {
            searchParams.append(key, value);
        }
    });

    urlObj.search = '?' + searchParams;

    return urlObj.href;
};

export default customInstance;

export class QueryError extends Error {
    public readonly url: string;
    public readonly status: number;
    public readonly statusText: string;
    public readonly errorMessage: string | null;
    public readonly errorStack: string | null;

    constructor(res: Pick<SerializableResponse, 'url' | 'status' | 'statusText' | 'headers'>, error?: Error) {
        if (error && error instanceof QueryError)
            console.error('Inner error cannot be a QueryError', { error });

        const errorMessage = error?.message ?? QueryError.getHeaderContent(res.headers.get('error-message'));
        const errorStack = error?.stack ?? QueryError.getHeaderContent(res.headers.get('error-stack'));

        super("Query error:"
            + `\nurl = ${res.url}`
            + `\nstatus = ${res.status} / ${res.statusText}`
            + `\nerror message = ${errorMessage}`
            + `\nerror stack =\n${errorStack}`);

        this.url = res.url;
        this.status = res.status;
        this.statusText = res.statusText;
        this.errorMessage = errorMessage;
        this.errorStack = errorStack;

        Object.setPrototypeOf(this, QueryError.prototype);

        console.error(this.message);
    }

    private static getHeaderContent(value: string | null): string | null {
        try {
            return JSON.parse(value!);
        } catch (_) {
            return value;
        }
    }
}

